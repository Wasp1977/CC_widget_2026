# ── Helper ──
def add_p(text, bold=False):
    r = doc.add_paragraph()
    r.alignment = WD_ALIGN_PARAGRAPH.JUSTIFY
    r.paragraph_format.first_line_indent = Cm(1.25)
    run = r.add_run(text)
    run.bold = bold
    run.font.size = Pt(12)
    run.font.name = 'SimSun'
    return r

def add_bullet(text, level=0):
    r = doc.add_paragraph(style='List Bullet')
    r.clear()
    run = r.add_run(text)
    run.font.size = Pt(12)
    run.font.name = 'SimSun'
    r.paragraph_format.left_indent = Cm(1.25 + level * 0.9)
    return r

def add_table(headers, rows):
    t = doc.add_table(rows=1+len(rows), cols=len(headers))
    t.style = 'Table Grid'
    t.alignment = WD_TABLE_ALIGNMENT.CENTER
    for i, h in enumerate(headers):
        c = t.rows[0].cells[i]
        c.text = ''
        run = c.paragraphs[0].add_run(h)
        run.bold = True
        run.font.size = Pt(10.5)
        run.font.name = 'SimSun'
        run.font.color.rgb = RGBColor(0xFF, 0xFF, 0xFF)
        c.paragraphs[0].alignment = WD_ALIGN_PARAGRAPH.CENTER
        from docx.oxml.ns import qn
        shading = c._element.get_or_add_tcPr()
        shd = shading.makeelement(qn('w:shd'), {qn('w:val'):'clear', qn('w:color'):'auto', qn('w:fill'):'5B7FA5'})
        shading.append(shd)
    for ri, row in enumerate(rows):
        for ci, val in enumerate(row):
            c = t.rows[ri+1].cells[ci]
            c.text = ''
            run = c.paragraphs[0].add_run(val)
            run.font.size = Pt(10.5)
            run.font.name = 'SimSun'
            if ri % 2 == 1:
                shading = c._element.get_or_add_tcPr()
                shd = shading.makeelement(qn('w:shd'), {qn('w:val'):'clear', qn('w:color'):'auto', qn('w:fill'):'F0F4F8'})
                shading.append(shd)
    doc.add_paragraph()  # spacing after table
    return t

